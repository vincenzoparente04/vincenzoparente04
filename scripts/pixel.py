GLYPH_W, GLYPH_H = 5, 7
ADVANCE = 6  # glyph width + 1 pixel of spacing


def runs(bitmap, char="#"):
    """Yield (x, y, length) for each horizontal run of `char` in a bitmap."""
    for y, row in enumerate(bitmap):
        x = 0
        while x < len(row):
            if row[x] == char:
                start = x
                while x < len(row) and row[x] == char:
                    x += 1
                yield start, y, x - start
            else:
                x += 1


def bitmap_path(bitmap, px, ox=0.0, oy=0.0, char="#"):
    """SVG path data drawing a bitmap with square pixels of size `px`."""
    return "".join(
        f"M{ox + x * px:g} {oy + y * px:g}h{n * px:g}v{px:g}h{-n * px:g}z"
        for x, y, n in runs(bitmap, char)
    )


def text_width(text, px):
    return (len(text) * ADVANCE - 1) * px


def text_path(text, px, x=0.0, y=0.0):
    """SVG path data for `text` in the pixel font, top-left at (x, y)."""
    d = []
    for i, ch in enumerate(text):
        glyph = FONT.get(ch) or FONT.get(ch.upper()) or FONT[" "]
        d.append(bitmap_path(glyph, px, x + i * ADVANCE * px, y))
    return "".join(d)


def text(text_, px, x, y, cls="", attrs=""):
    c = f' class="{cls}"' if cls else ""
    return f'<path{c}{attrs} d="{text_path(text_, px, x, y)}"/>'
